const char* gsAbilityByDescription(const char* text, unsigned* idOut) {
	int found = -1;
	bool tla = gsRam() == &gsRamTla;
	const char* const* dt = tla ? descsTla : descs;
	unsigned dn = tla ? sizeof(descsTla) / sizeof(descsTla[0]) : sizeof(descs) / sizeof(descs[0]);
	for (unsigned i = 0; i < dn; ++i) {
		if (!dt[i] || strcmp(dt[i], text)) continue;
		if (found >= 0) return NULL;   // several abilities share this text: do not guess
		found = (int) i;
	}
	if (found < 0) return NULL;
	if (idOut) *idOut = (unsigned) found;
	return gsAbilityName((unsigned) found);
}


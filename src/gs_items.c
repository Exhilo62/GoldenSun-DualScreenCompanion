const char* gsItemName(unsigned id) {
	bool tla = gsRam() == &gsRamTla;
	const char* const* t = tla ? namesTla : names;
	unsigned n = tla ? sizeof(namesTla) / sizeof(namesTla[0]) : sizeof(names) / sizeof(names[0]);
	if (id < n && t[id]) return t[id];
	return "?";
}

# Bakes the tab icons (from the mockup) and the eight party portraits (from the game's own status-screen art) into src/art_data.c.
# Sources (in assets/reference/): map_mockup.webp (tab icons), <name>_game.png (portraits).
# Run: powershell -ExecutionPolicy Bypass -File tools/genart.ps1
Add-Type -AssemblyName PresentationCore, WindowsBase, System.Drawing
$root = Resolve-Path "$PSScriptRoot\.."
$ref = "$root\assets\reference"

function Load-Bitmap($path) {
    $fs = [System.IO.File]::OpenRead($path)
    $dec = [System.Windows.Media.Imaging.BitmapDecoder]::Create($fs, 'None', 'OnLoad')
    $enc = New-Object System.Windows.Media.Imaging.PngBitmapEncoder
    $enc.Frames.Add([System.Windows.Media.Imaging.BitmapFrame]::Create($dec.Frames[0]))
    $ms = New-Object System.IO.MemoryStream; $enc.Save($ms); $fs.Close(); $ms.Position = 0
    return [System.Drawing.Bitmap]::new($ms)
}
$full = Load-Bitmap "$ref\full_mockup.webp"   # 1536x1024
$map = Load-Bitmap "$ref\map_mockup.webp"     # 1469x1071

# name, source bitmap, left, top, right, bottom (inset a few px so the frame studs stay out)
$icons = @(
    @('party',    $map, 34, 26, 241, 164),
    @('psynergy', $map, 289, 26, 491, 164),
    @('djinn',    $map, 539, 26, 731, 164),
    @('map',      $map, 779, 26, 981, 164),
    @('items',    $map, 1022, 26, 1218, 164),
    @('menu',     $map, 1259, 26, 1441, 164)
)

function Resize($bmp, $l, $t, $r, $b, $w, $h) {
    $dst = New-Object System.Drawing.Bitmap $w, $h, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($dst)
    $g.InterpolationMode = 'HighQualityBicubic'; $g.PixelOffsetMode = 'Half'; $g.SmoothingMode = 'HighQuality'
    $g.DrawImage($bmp, (New-Object System.Drawing.Rectangle 0, 0, $w, $h), (New-Object System.Drawing.Rectangle $l, $t, ($r - $l), ($b - $t)), 'Pixel')
    $g.Dispose()
    return $dst
}

function Emit($sb, $id, $bmp, $mode) {
    $withAlpha = $mode -ne 'opaque'
    $w = $bmp.Width; $h = $bmp.Height
    # Background estimate for the alpha key: mean of the four corner pixels.
    $bg = @(0, 0, 0)
    foreach ($p in @(@(0, 0), @(($w - 1), 0), @(0, ($h - 1)), @(($w - 1), ($h - 1)))) { $c = $bmp.GetPixel($p[0], $p[1]); $bg[0] += $c.R / 4; $bg[1] += $c.G / 4; $bg[2] += $c.B / 4 }
    $cols = New-Object System.Text.StringBuilder; $alp = New-Object System.Text.StringBuilder
    for ($y = 0; $y -lt $h; $y++) {
        for ($x = 0; $x -lt $w; $x++) {
            $c = $bmp.GetPixel($x, $y)
            $v = (([int]$c.R -shr 3) -shl 11) -bor (([int]$c.G -shr 2) -shl 5) -bor ([int]$c.B -shr 3)
            [void]$cols.Append($v).Append(',')
            if ($withAlpha) {
                if ($mode -eq 'dist') {
                    $d = [math]::Max([math]::Abs($c.R - $bg[0]), [math]::Max([math]::Abs($c.G - $bg[1]), [math]::Abs($c.B - $bg[2])))
                    $a = [math]::Min(255, [math]::Max(0, ($d - 10) * 6))
                } else {
                    $lum = 0.3 * $c.R + 0.59 * $c.G + 0.11 * $c.B
                    if ($mode -eq 'lumframe') { $a = [math]::Min(255, [math]::Max(0, ($lum - 45) * 4.5)) }
                    else { $a = [math]::Min(230, [math]::Max(0, ($lum - 62) * 3.2)) }     # compass: faint watermark
                }
                [void]$alp.Append([int]$a).Append(',')
            }
        }
        [void]$cols.Append("`n")
        if ($withAlpha) { [void]$alp.Append("`n") }
    }
    [void]$sb.AppendLine("static const uint16_t ${id}_c[$($w * $h)] = {"); [void]$sb.Append($cols.ToString()); [void]$sb.AppendLine('};')
    if ($withAlpha) { [void]$sb.AppendLine("static const uint8_t ${id}_a[$($w * $h)] = {"); [void]$sb.Append($alp.ToString()); [void]$sb.AppendLine('};') }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by tools/genart.ps1 from assets/reference/*.webp (the project mockups). Do not edit.')
[void]$sb.AppendLine('#include "art_data.h"')
[void]$sb.AppendLine('')
$i = 0
foreach ($ic in $icons) {
    Emit $sb "iconBig$i" (Resize $ic[1] $ic[2] $ic[3] $ic[4] $ic[5] 46 32) 'dist'
    Emit $sb "iconSmall$i" (Resize $ic[1] $ic[2] $ic[3] $ic[4] $ic[5] 29 20) 'dist'
    $i++
}
$i = 0
# Portraits: the game's own 32x32 status-screen art for all eight characters (captured to assets/reference/<name>_game.png, flat backdrop
# already replaced by the app's navy gradient), cropped and scaled to 68x46. Order = character record order.
foreach ($n in @('Isaac', 'Garet', 'Ivan', 'Mia', 'Felix', 'Jenna', 'Sheba', 'Piers')) {
    $gp = [System.Drawing.Bitmap]::new("$ref\${n}_game.png")
    Emit $sb "portrait$i" (Resize $gp 0 6 32 28 68 46) 'opaque'; $i++
}
# Frame corner (bottom-left corner of the map panel), faint compass rose, and a 320x240 cloud background that tiles by mirroring.
Emit $sb 'cornerBL' (Resize $map 12 692 108 788 22 22) 'lumframe'
Emit $sb 'compass' (Resize $map 1142 382 1438 678 64 64) 'lumcompass'
$cloud = Resize $map 54 368 454 752 240 240
$wide = New-Object System.Drawing.Bitmap 480, 240
$gw = [System.Drawing.Graphics]::FromImage($wide); $gw.DrawImage($cloud, 0, 0, 240, 240)
$flip = $cloud.Clone(); $flip.RotateFlip([System.Drawing.RotateFlipType]::RotateNoneFlipX); $gw.DrawImage($flip, 240, 0, 240, 240); $gw.Dispose()
$bgImg = New-Object System.Drawing.Bitmap 320, 240
$gb = [System.Drawing.Graphics]::FromImage($bgImg); $gb.DrawImage($wide, (New-Object System.Drawing.Rectangle 0, 0, 320, 240), (New-Object System.Drawing.Rectangle 0, 0, 320, 240), 'Pixel'); $gb.Dispose()
Emit $sb 'background' $bgImg 'opaque'
[void]$sb.AppendLine('const ArtImage artBakedCorner = {22, 22, cornerBL_c, cornerBL_a};')
[void]$sb.AppendLine('const ArtImage artBakedCompass = {64, 64, compass_c, compass_a};')
[void]$sb.AppendLine('const uint16_t* const artBakedBackground = background_c;')
[void]$sb.AppendLine('const ArtImage artBakedIconBig[6] = {')
for ($k = 0; $k -lt 6; $k++) { [void]$sb.AppendLine("\t{46, 32, iconBig${k}_c, iconBig${k}_a},") }
[void]$sb.AppendLine('};'); [void]$sb.AppendLine('const ArtImage artBakedIconSmall[6] = {')
for ($k = 0; $k -lt 6; $k++) { [void]$sb.AppendLine("\t{29, 20, iconSmall${k}_c, iconSmall${k}_a},") }
[void]$sb.AppendLine('};'); [void]$sb.AppendLine('const ArtImage artBakedPortrait[8] = {')
for ($k = 0; $k -lt 8; $k++) { [void]$sb.AppendLine("\t{68, 46, portrait${k}_c, 0},") }
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('const char* const artBakedPortraitNames[8] = {"Isaac", "Garet", "Ivan", "Mia", "Felix", "Jenna", "Sheba", "Piers"};')
[System.IO.File]::WriteAllText("$root\src\art_data.c", $sb.ToString().Replace('\t', "`t"))
Write-Host "wrote src/art_data.c ($((Get-Item "$root\src\art_data.c").Length) bytes)"

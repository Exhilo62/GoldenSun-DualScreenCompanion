"""Builds the Lost Age area-name table (src/gs_areas_tla.inc) from the game's own text: internal map labels are text ids 0xE00+186+map id (decoded
by tools/ta_textdec.py into build/td_14.txt), the player-facing location names are text ids 0xE00+88..170. Labels whose prefix clearly belongs to a
location (same order in both lists, confirmed on maps 0x10F Prox, 0x11F Mars Lighthouse, 0x134 Anemos Sanctum) get the location name; the rest
show the internal label so nothing is mislabelled."""
import re
T = {}
for g in (14, 15):
    for l in open(f'build/td_{g}.txt'):
        m = re.match(r"(\d+) (\d+) (.*)$", l.strip())
        if m: T[(int(m.group(1)) << 8) | int(m.group(2))] = eval(m.group(3))
RULES = [  # (regex on the internal label, location name)
 (r'^TITLE$', 'Title Screen'), (r'^UTIL$', 'Clear Data'), (r'^WORLD$', 'World Map'), (r'^WORLD_END$', 'Staff Credits'),
 (r'^(V_ENT|VTO)', 'Venus Lighthouse'), (r'^SHR_M', 'Suhalla Gate'),
 (r'^(DELY|DLY_|DL_SINDEN)', 'Daila'), (r'^(KANDRA|KANDO)', 'Kandorean Temple'), (r'^KAIJIN', 'Shrine of the Sea God'),
 (r'^(DEKAN|DJ_DKN)', 'Dehkan Plateau'), (r'^(REM_FUNE|REM_SHIP)', 'Lemurian Ship'), (r'^(MD_ROOM|DJ_MDR)', 'Madra'),
 (r'^(MEEKA|MEEB|MI_ROOM|MI_SINDEN)', 'Mikasalla'), (r'^(POPEE|PO_ROOM|PO_SINDEN)', 'Garoh'),
 (r'^(YANPI|DJ_YANPI)', 'Yampi Desert'), (r'^(AYERES|AR_IN)', "Air's Rock"), (r'^AF_ROOM', 'Alhafra'),
 (r'^(NIRI|NR_ROOM)', 'Naribwe'), (r'^(KBMB|KB_ROOM|DJ_KB)', 'Kibombo'), (r'^(DJ_GBM|GBM)', 'Gabomba'),
 (r'^(YARRAM|YA_ROOM)', 'Yallam'), (r'^TAUPO', 'Taopo Swamp'), (r'^AQUAR', 'Aqua Rock'), (r'^GAIAR', 'Gaia Rock'),
 (r'^(IZUMO|IZ_ROOM)', 'Izumo'), (r'^(CHAM$|CHAM[0-9]|CH_ROOM|CH_SINDEN)', 'Champa'), (r'^ANGKOR', 'Ankohl Ruins'),
 (r'^REM_OLD', 'Ancient Lemuria'), (r'^(REMURIA|REM_ROOM|REM_CAS|REM_IZU)', 'Lemuria'),
 (r'^GND_', 'Gondowan Settlement'), (r'^HES_', 'Hesperia Settlement'), (r'^KLT_', 'Kalt Island'),
 (r'^(MAGMA|MAGR)', 'Magma Rock'), (r'^ATK_IRIE', 'Atteka Inlet'), (r'^(SHARMAN|SHA_ROOM|SHA_SINDEN)', 'Shaman Village'),
 (r'^TRYROAD', 'Trial Road'), (r'^JTO', 'Jupiter Lighthouse'), (r'^(ROOFO|RO_ROOM)', 'Loho'), (r'^KITA_UMI', 'Northern Reaches'),
 (r'^(PROX|PRO_ROOM|PRO_SINDEN)', 'Prox'), (r'^DJ_IND', 'Indra Cavern'), (r'^DJ_OSE', 'Osenia Cavern'), (r'^DJ_ANG', 'Angara Cavern'),
 (r'^DJ_ATK', 'Atteka Cavern'), (r'^MAR_', 'Mars Lighthouse'), (r'^TAKARA', 'Treasure Isle'), (r'^ANEMOS', 'Anemos Sanctum'),
 (r'^EPILOGUE', 'Epilogue'),
 # added Oct 26: the rest of the families whose prefix is unambiguous (RITOU = islet, TEIHAKU = anchored, MTO = Mars tower like JTO; the test rooms are debug maps)
 (r'^CHAM_', 'Champa'), (r'^(RITOU|DJ_RITOU)', 'Islet Cave'), (r'^TEIHAKU', 'Lemurian Ship'), (r'^REM_D$', 'Lemuria'), (r'^MTO', 'Mars Lighthouse'),
 (r'^ALFA', 'Alhafra'), (r'^GIA_ROOM', 'Gaia Rock'), (r'^(TEST|YAMTEST|SHOPTEST|GET_ITEM|ROUNGE)', 'Debug map'),
]
out = []
named = 0
for mid in range(0, 325):
    lab = T.get(0xE00 + 186 + mid)
    if not lab or lab == '?': continue
    name = None
    for pat, loc in RULES:
        if re.match(pat, lab): name = loc; break
    if name: named += 1
    elif lab.startswith('OTMP'): name = 'Unused map'   # placeholder map
    else: name = lab.replace('_', ' ').title()
    out.append((mid, name))
open('src/gs_areas_tla.inc', 'w').write('// Generated by tools/gen_ta_areas.py from The Lost Age\'s own text. Do not edit.\n' + ''.join('\t{0x%03X, "%s"},\n' % (m, n.replace('"', '')) for m, n in out))
print(len(out), 'maps,', named, 'with a location name')

"""Writes src/gs_classes_tla.inc from the decoded Lost Age text: python tools/ta_textdec.py 11 > build/ta_g11.txt; python tools/ta_textdec.py 12 > build/ta_g12.txt
(class id = text index - 99 in group 11, 157 + index in group 12; ids 0..92 match Golden Sun's)."""
import re
names = {}
for fn, grp in (('build/ta_g11.txt', 11), ('build/ta_g12.txt', 12)):
    for line in open(fn):
        m = re.match(r"(\d+) (\d+) '(.*)'", line.strip())
        if not m:
            continue
        g, i, t = int(m.group(1)), int(m.group(2)), m.group(3)
        cid = (i - 99) if g == 11 else 157 + i
        if t in ('?', '') or '<' in t or (g == 11 and i < 99) or cid > 248:   # past id 248 the text is battle messages
            continue
        names[cid] = t
out = ['// Generated by tools/gen_ta_classes.py from The Lost Age text groups 11 (class id = index - 99) and 12 (index + 157). Do not edit.', 'static const char* const namesTla[%d] = {' % (max(names) + 1)]
out += ['\t[%d] = "%s",' % (k, names[k].replace('"', '\\"')) for k in sorted(names)]
out.append('};')
open('src/gs_classes_tla.inc', 'w', newline='\n').write('\n'.join(out) + '\n')

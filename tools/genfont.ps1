# Rasterizes the UI fonts into src/font_data.c (alpha bitmaps for ASCII 32..126).
# Source: Ubuntu Font Family (Ubuntu Font Licence 1.0, Canonical Ltd). Run: powershell -File tools/genfont.ps1
param(
    [string]$FontDir = $env:UBUNTU_FONT_DIR,   # folder with Ubuntu-R.ttf / Ubuntu-B.ttf (Ubuntu Font Licence)
    [string]$Out = "$PSScriptRoot\..\src\font_data.c"
)
Add-Type -AssemblyName System.Drawing

# name, file, pixel size
$specs = @(
    @{ id = 'tiny';  file = 'Ubuntu-B.ttf'; px = 10 },
    @{ id = 'small'; file = 'Ubuntu-M.ttf'; px = 11 },
    @{ id = 'large'; file = 'Ubuntu-B.ttf'; px = 16 }
)
$sf = [System.Drawing.StringFormat]::GenericTypographic
$sf.FormatFlags = $sf.FormatFlags -bor [System.Drawing.StringFormatFlags]::MeasureTrailingSpaces
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by tools/genfont.ps1 from the Ubuntu Font Family (Ubuntu Font Licence 1.0). Do not edit.')
[void]$sb.AppendLine('#include "font_data.h"')
[void]$sb.AppendLine('')

foreach ($spec in $specs) {
    $pfc = New-Object System.Drawing.Text.PrivateFontCollection
    $pfc.AddFontFile($FontDir + $spec.file)
    $fam = $pfc.Families[0]
    $font = New-Object System.Drawing.Font($fam, [single]$spec.px, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
    $em = $fam.GetEmHeight([System.Drawing.FontStyle]::Regular)
    $asc = [math]::Ceiling($fam.GetCellAscent([System.Drawing.FontStyle]::Regular) * $spec.px / $em)
    $dsc = [math]::Ceiling($fam.GetCellDescent([System.Drawing.FontStyle]::Regular) * $spec.px / $em)
    $H = [int]($asc + $dsc)
    $meas = New-Object System.Drawing.Bitmap 8, 8
    $mg = [System.Drawing.Graphics]::FromImage($meas)
    $mg.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
    $base = $mg.MeasureString('||', $font, 1000, $sf).Width

    function Render([string]$ch, [int]$w) {
        $b = New-Object System.Drawing.Bitmap $w, $H
        $g = [System.Drawing.Graphics]::FromImage($b)
        $g.Clear([System.Drawing.Color]::Black)
        $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
        $g.DrawString($ch, $font, [System.Drawing.Brushes]::White, 1, 0, $sf)
        $g.Dispose()
        return $b
    }

    # Cap top = first inked row of 'H'.
    $hb = Render 'H' 24
    $capTop = 0
    :find for ($y = 0; $y -lt $H; $y++) { for ($x = 0; $x -lt 24; $x++) { if ($hb.GetPixel($x, $y).R -gt 80) { $capTop = $y; break find } } }
    $capBottom = 0
    for ($y = $H - 1; $y -ge 0; $y--) { $hit = $false; for ($x = 0; $x -lt 24; $x++) { if ($hb.GetPixel($x, $y).R -gt 80) { $hit = $true; break } }; if ($hit) { $capBottom = $y; break } }
    $capH = $capBottom - $capTop + 1

    $advs = @(); $offs = @(); $data = New-Object System.Collections.Generic.List[int]
    for ($c = 32; $c -le 126; $c++) {
        $ch = [string][char]$c
        $adv = [int][math]::Round($mg.MeasureString("|$ch|", $font, 1000, $sf).Width - $base)
        if ($adv -lt 2) { $adv = 2 }
        $w = $adv + 2
        $b = Render $ch $w
        $advs += $adv; $offs += $data.Count
        for ($y = 0; $y -lt $H; $y++) { for ($x = 0; $x -lt $w; $x++) { $data.Add([int]$b.GetPixel($x, $y).R) } }
        $b.Dispose()
    }
    [void]$sb.AppendLine("static const uint8_t $($spec.id)_adv[95] = {" + ($advs -join ',') + '};')
    [void]$sb.AppendLine("static const uint32_t $($spec.id)_off[95] = {" + ($offs -join ',') + '};')
    [void]$sb.AppendLine("static const uint8_t $($spec.id)_data[] = {")
    $line = New-Object System.Text.StringBuilder
    for ($i = 0; $i -lt $data.Count; $i++) {
        [void]$line.Append($data[$i]); [void]$line.Append(',')
        if ($line.Length -gt 110) { [void]$sb.AppendLine($line.ToString()); [void]$line.Clear() }
    }
    [void]$sb.AppendLine($line.ToString()); [void]$sb.AppendLine('};')
    [void]$sb.AppendLine("const GFont font_$($spec.id) = { $H, $capTop, $capH, $($spec.id)_adv, $($spec.id)_off, $($spec.id)_data };")
    [void]$sb.AppendLine('')
    Write-Host "$($spec.id): px=$($spec.px) cell h=$H capTop=$capTop capH=$capH glyph bytes=$($data.Count)"
}
[System.IO.File]::WriteAllText((Resolve-Path (Split-Path $Out)).Path + '\' + (Split-Path $Out -Leaf), $sb.ToString())
Write-Host "wrote $Out"

"""Bakes the item icons (16x16, Golden Sun and The Lost Age have different id->icon tables) and the four Djinn element sprites (24x30, shared)
from assets/reference/gs1_icons/*.rgb and assets/reference/tla_icons/*.rgb into src/icon_data.c.
The .rgb files are raw 8-bit RGB crops of the game's own menus (tools/itemicons.py and the Status screen); the menu backdrop colour (0,24,99) becomes transparent.
Run: python tools/genicons.py"""
import glob, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, 'assets', 'reference', 'gs1_icons')
BG = (0, 24, 99)        # Golden Sun menu backdrop
BG_TLA = (0, 107, 140)  # The Lost Age menu backdrop
def conv(raw, bg=BG):
    col, alp = [], []
    for i in range(0, len(raw), 3):
        r, g, b = raw[i], raw[i + 1], raw[i + 2]
        col.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)); alp.append(0 if (r, g, b) == bg else 255)
    return col, alp
out = ["// Generated by tools/genicons.py from assets/reference/{gs1,tla}_icons (the games' own menu art). Do not edit.", '#include "art_data.h"', '']
def items(tag, folder, bgc, stem='item', sym='Item'):
    d = os.path.join(root, 'assets', 'reference', folder)
    ids = sorted(int(re.search(stem + '_(' + chr(92) + 'd+)', f).group(1)) for f in glob.glob(os.path.join(d, stem + '_*.rgb')))
    cols, alps = [], []
    for i in ids:
        c, a = conv(open(os.path.join(d, f'{stem}_{i}.rgb'), 'rb').read(), bgc); cols += c; alps += a
    n = len(ids)
    out.append(f'const int art{sym}IconCount{tag} = {n};')
    out.append(f'const uint16_t art{sym}IconIds{tag}[{n}] = {{' + ','.join(map(str, ids)) + '};')
    out.append(f'static const uint16_t {stem}Col{tag}[{n * 256}] = {{' + ','.join(map(str, cols)) + '};')
    out.append(f'static const uint8_t {stem}Alpha{tag}[{n * 256}] = {{' + ','.join(map(str, alps)) + '};')
    out.append(f'const ArtImage art{sym}IconImages{tag}[{n}] = {{' + ','.join(f'{{16,16,{stem}Col{tag}+{k * 256},{stem}Alpha{tag}+{k * 256}}}' for k in range(n)) + '};')
    return n
n1 = items('', 'gs1_icons', BG)
n2 = items('Tla', 'tla_icons', BG_TLA)
n = n1
items('', 'gs1_psy', (255, 0, 255), 'psy', 'Psy')
items('Tla', 'tla_psy', (255, 0, 255), 'psy', 'Psy')
dj = []
for k, nm in enumerate(('venus', 'mars', 'jupiter', 'mercury')):   # GS_VENUS, GS_MARS, GS_JUPITER, GS_MERCURY
    c, a = conv(open(os.path.join(src, f'djinn_{nm}.rgb'), 'rb').read())
    out.append(f'static const uint16_t djc{k}[720] = {{' + ','.join(map(str, c)) + '};')
    out.append(f'static const uint8_t dja{k}[720] = {{' + ','.join(map(str, a)) + '};')
    dj.append(f'{{24,30,djc{k},dja{k}}}')
out.append('const ArtImage artDjinnImages[4] = {' + ','.join(dj) + '};')
open(os.path.join(root, 'src', 'icon_data.c'), 'w').write('\n'.join(out) + '\n')
print('wrote src/icon_data.c:', n1, 'Golden Sun and', n2, 'Lost Age item icons, plus Psynergy icons')

# Bakes the game-pick cards' fan art (assets/reference/card_logo_gs1.png, card_logo_gs2.webp: the game logos; card_face_gs1/2.webp: framed portraits)
# into src/card_data.c as RGB565 + alpha sprites. Run: powershell -ExecutionPolicy Bypass -File tools/gencards.ps1
Add-Type -AssemblyName PresentationCore, WindowsBase, System.Drawing
$root = Resolve-Path "$PSScriptRoot\.."
$ref = "$root\assets\reference"
function Load-Bitmap($path) {
    $fs = [System.IO.File]::OpenRead($path)
    $dec = [System.Windows.Media.Imaging.BitmapDecoder]::Create($fs, 'None', 'OnLoad')
    $enc = New-Object System.Windows.Media.Imaging.PngBitmapEncoder
    $enc.Frames.Add([System.Windows.Media.Imaging.BitmapFrame]::Create($dec.Frames[0]))
    $ms = New-Object System.IO.MemoryStream; $enc.Save($ms); $fs.Close(); $ms.Position = 0
    return [System.Drawing.Bitmap]::new($ms)
}
$LOGO_W = 214; $LOGO_H = 54; $FACE = 60
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by tools/gencards.ps1 from assets/reference/card_*. Do not edit.')
[void]$sb.AppendLine('#include "art.h"')
$sprites = @()
$items = @(@('logo', 'card_logo_gs1.png'), @('logo', 'card_logo_gs2.webp'), @('face', 'card_face_gs1.webp'), @('face', 'card_face_gs2.webp'))
for ($n = 0; $n -lt 4; ++$n) {
    $kind = $items[$n][0]
    $src = Load-Bitmap "$ref\$($items[$n][1])"
    $cornerA = $src.GetPixel(2, 2).A
    # logos: use the alpha channel when there is one, otherwise key out the black backdrop; then trim to the visible bounds
    $x0 = $src.Width; $y0 = $src.Height; $x1 = 0; $y1 = 0
    if ($kind -eq 'logo') {
        $full = New-Object System.Drawing.Bitmap $src.Width, $src.Height, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
        for ($y = 0; $y -lt $src.Height; ++$y) { for ($x = 0; $x -lt $src.Width; ++$x) {
            $p = $src.GetPixel($x, $y)
            $a = $p.A
            if ($cornerA -eq 255) { $lum = [Math]::Max($p.R, [Math]::Max($p.G, $p.B)); $a = [Math]::Min(255, [Math]::Max(0, [int](($lum - 14) * 255 / 40))) }
            $full.SetPixel($x, $y, [System.Drawing.Color]::FromArgb($a, $p.R, $p.G, $p.B))
            if ($a -gt 24) { if ($x -lt $x0) { $x0 = $x }; if ($x -gt $x1) { $x1 = $x }; if ($y -lt $y0) { $y0 = $y }; if ($y -gt $y1) { $y1 = $y } }
        } }
        $cw = $x1 - $x0 + 1; $ch = $y1 - $y0 + 1
        $scale = [Math]::Min($LOGO_W / $cw, $LOGO_H / $ch)
        $w = [int][Math]::Round($cw * $scale); $h = [int][Math]::Round($ch * $scale)
        $srcRect = New-Object System.Drawing.Rectangle $x0, $y0, $cw, $ch
        $srcBmp = $full
    } else {
        $w = $FACE; $h = $FACE
        $srcRect = New-Object System.Drawing.Rectangle 0, 0, $src.Width, $src.Height
        $srcBmp = $src
    }
    $dst = New-Object System.Drawing.Bitmap $w, $h, ([System.Drawing.Imaging.PixelFormat]::Format32bppPArgb)
    $g = [System.Drawing.Graphics]::FromImage($dst)
    $g.InterpolationMode = 'HighQualityBicubic'; $g.PixelOffsetMode = 'HighQuality'; $g.SmoothingMode = 'HighQuality'; $g.Clear([System.Drawing.Color]::Transparent)
    $g.DrawImage($srcBmp, (New-Object System.Drawing.Rectangle 0, 0, $w, $h), $srcRect.X, $srcRect.Y, $srcRect.Width, $srcRect.Height, [System.Drawing.GraphicsUnit]::Pixel)
    $g.Dispose()
    $col = New-Object System.Collections.Generic.List[string]; $alp = New-Object System.Collections.Generic.List[string]
    for ($y = 0; $y -lt $h; ++$y) { for ($x = 0; $x -lt $w; ++$x) {
        $p = $dst.GetPixel($x, $y)
        $col.Add([string]((([int]$p.R -shr 3) -shl 11) -bor (([int]$p.G -shr 2) -shl 5) -bor ([int]$p.B -shr 3))); $alp.Add([string]$p.A)
    } }
    [void]$sb.AppendLine("static uint16_t col$n[$($w * $h)] = {" + ($col -join ',') + '};')
    [void]$sb.AppendLine("static uint8_t alp$n[$($w * $h)] = {" + ($alp -join ',') + '};')
    $sprites += "{$w, $h, col$n, alp$n}"
    $prev = New-Object System.Drawing.Bitmap ($w * 3), ($h * 3)
    $pg = [System.Drawing.Graphics]::FromImage($prev); $pg.Clear([System.Drawing.Color]::FromArgb(14, 30, 80))
    $pg.InterpolationMode = 'NearestNeighbor'; $pg.PixelOffsetMode = 'Half'; $pg.DrawImage($dst, 0, 0, $w * 3, $h * 3); $pg.Dispose()
    $prev.Save("$root\build\card_preview_$n.png", [System.Drawing.Imaging.ImageFormat]::Png)
    Write-Output "$($items[$n][1]): corner alpha $cornerA -> ${w}x${h}"
    $src.Dispose()
}
[void]$sb.AppendLine('static Sprite sprites[4] = {' + ($sprites -join ', ') + '};')
[void]$sb.AppendLine('const Sprite* artCardLogo(int game) { return &sprites[game ? 1 : 0]; }')
[void]$sb.AppendLine('const Sprite* artCardFace(int game) { return &sprites[game ? 3 : 2]; }')
[System.IO.File]::WriteAllText("$root\src\card_data.c", $sb.ToString())

# Bakes the Map tab's Center and Zoom button icons (assets/reference/map_center_icon.png, map_zoom_icon.png: gold icons on the navy button)
# into src/mapicon_data.c as RGB565 + alpha sprites. The navy background is keyed out by how far a pixel is from the corner colour.
# Run: powershell -ExecutionPolicy Bypass -File tools/genmapicons.ps1
Add-Type -AssemblyName System.Drawing
$root = Resolve-Path "$PSScriptRoot\.."
$H = 20
$names = @('map_center_icon', 'map_zoom_icon')
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by tools/genmapicons.ps1 from assets/reference/map_*_icon.png. Do not edit.')
[void]$sb.AppendLine('#include "art.h"')
$sprites = @()
for ($n = 0; $n -lt 2; ++$n) {
    $src = [System.Drawing.Bitmap]::new("$root\assets\reference\$($names[$n]).png")
    $bg = $src.GetPixel(2, 2)
    $x0 = $src.Width; $y0 = $src.Height; $x1 = 0; $y1 = 0
    $al = New-Object 'int[,]' $src.Width, $src.Height
    for ($y = 0; $y -lt $src.Height; ++$y) { for ($x = 0; $x -lt $src.Width; ++$x) {
        $p = $src.GetPixel($x, $y)
        $d = [Math]::Max([Math]::Abs($p.R - $bg.R), [Math]::Max([Math]::Abs($p.G - $bg.G), [Math]::Abs($p.B - $bg.B))); $a = [Math]::Max(0, [Math]::Min(255, [int](($d - 18) * 255 / 70)))
        $al[$x, $y] = $a
        if ($a -gt 60) { if ($x -lt $x0) { $x0 = $x }; if ($x -gt $x1) { $x1 = $x }; if ($y -lt $y0) { $y0 = $y }; if ($y -gt $y1) { $y1 = $y } }
    } }
    $cw = $x1 - $x0 + 1; $ch = $y1 - $y0 + 1
    $crop = New-Object System.Drawing.Bitmap $cw, $ch, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    for ($y = 0; $y -lt $ch; ++$y) { for ($x = 0; $x -lt $cw; ++$x) {
        $p = $src.GetPixel($x0 + $x, $y0 + $y); $a = $al[($x0 + $x), ($y0 + $y)]
        $r = [Math]::Min(255, [int]($p.R * 255 / [Math]::Max(1, $a) * 0 + $p.R)); 
        $crop.SetPixel($x, $y, [System.Drawing.Color]::FromArgb($a, $p.R, $p.G, $p.B))
    } }
    $w = [Math]::Max(1, [int][Math]::Round($cw * $H / $ch))
    $dst = New-Object System.Drawing.Bitmap $w, $H, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($dst)
    $g.InterpolationMode = 'HighQualityBicubic'; $g.PixelOffsetMode = 'HighQuality'; $g.Clear([System.Drawing.Color]::Transparent)
    $g.DrawImage($crop, 0, 0, $w, $H); $g.Dispose()
    $col = New-Object System.Collections.Generic.List[string]; $alp = New-Object System.Collections.Generic.List[string]
    for ($y = 0; $y -lt $H; ++$y) { for ($x = 0; $x -lt $w; ++$x) {
        $p = $dst.GetPixel($x, $y)
        $col.Add([string]((([int]$p.R -shr 3) -shl 11) -bor (([int]$p.G -shr 2) -shl 5) -bor ([int]$p.B -shr 3))); $alp.Add([string]$p.A)
    } }
    [void]$sb.AppendLine("static uint16_t col$n[$($w * $H)] = {" + ($col -join ',') + '};')
    [void]$sb.AppendLine("static uint8_t alp$n[$($w * $H)] = {" + ($alp -join ',') + '};')
    $sprites += "{$w, $H, col$n, alp$n}"
    $prev = New-Object System.Drawing.Bitmap ($w * 4), ($H * 4)
    $pg = [System.Drawing.Graphics]::FromImage($prev); $pg.Clear([System.Drawing.Color]::FromArgb(14, 30, 80))
    $pg.InterpolationMode = 'NearestNeighbor'; $pg.PixelOffsetMode = 'Half'; $pg.DrawImage($dst, 0, 0, $w * 4, $H * 4); $pg.Dispose()
    $prev.Save("$root\build\mapicon_preview_$n.png", [System.Drawing.Imaging.ImageFormat]::Png)
    $src.Dispose()
}
[void]$sb.AppendLine('static Sprite sprites[2] = {' + ($sprites -join ', ') + '};')
[void]$sb.AppendLine('const Sprite* artMapIcon(int id) { return &sprites[id ? 1 : 0]; }')
[System.IO.File]::WriteAllText("$root\src\mapicon_data.c", $sb.ToString())
Write-Output 'wrote src/mapicon_data.c'

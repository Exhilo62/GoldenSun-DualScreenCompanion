# Bakes the Golden Sun logo (assets/reference/logo.png) into src/logo_data.c as a 150-wide RGB565 + alpha image for the launcher's title card, and the HOME menu banner (assets/banner.png).
# Run: powershell -ExecutionPolicy Bypass -File tools/genlogo.ps1
Add-Type -AssemblyName System.Drawing
$root = Resolve-Path "$PSScriptRoot\.."
. "$PSScriptRoot\keyblack.ps1"
$src = Load-KeyedBitmap "$root\assets\reference\logo.png"
$SW = $src.Width; $SH = $src.Height
# HOME menu banner (256x128, logo centred on a transparent background)
$ban = New-Object System.Drawing.Bitmap 256, 128, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$gb = [System.Drawing.Graphics]::FromImage($ban); $gb.InterpolationMode = 'HighQualityBicubic'; $gb.PixelOffsetMode = 'Half'
$gb.DrawImage($src, 4, [int]((128 - 248 * $SH / $SW) / 2), 248, [int](248 * $SH / $SW)); $gb.Dispose(); $ban.Save("$root\assets\banner.png")

$W = 150; $H = [int][math]::Round(150 * $SH / $SW)
$hasAlpha = $true
# Work at 4x, then average down (alpha-weighted), so the soft edge of the logo stays clean at 144x72.
$big = New-Object System.Drawing.Bitmap ($W * 4), ($H * 4), ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$g = [System.Drawing.Graphics]::FromImage($big)
$g.InterpolationMode = 'HighQualityBicubic'; $g.PixelOffsetMode = 'Half'
$g.DrawImage($src, 0, 0, ($W * 4), ($H * 4)); $g.Dispose()
$cols = New-Object System.Text.StringBuilder; $alp = New-Object System.Text.StringBuilder
for ($y = 0; $y -lt $H; $y++) {
    for ($x = 0; $x -lt $W; $x++) {
        $r = 0.0; $gg = 0.0; $b = 0.0; $a = 0.0
        for ($j = 0; $j -lt 4; $j++) { for ($i = 0; $i -lt 4; $i++) {
            $c = $big.GetPixel($x * 4 + $i, $y * 4 + $j)
            $al = $c.A / 255.0
            $r += $c.R * $al; $gg += $c.G * $al; $b += $c.B * $al; $a += $al
        } }
        if ($a -gt 0.01) { $r /= $a; $gg /= $a; $b /= $a }
        $v = (([int]$r -shr 3) -shl 11) -bor (([int]$gg -shr 2) -shl 5) -bor ([int]$b -shr 3)
        [void]$cols.Append($v).Append(','); [void]$alp.Append([int]($a / 16 * 255)).Append(',')
    }
    [void]$cols.Append("`n"); [void]$alp.Append("`n")
}
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by tools/genlogo.ps1 from assets/reference/logo.png. Do not edit.')
[void]$sb.AppendLine('#include "art_data.h"')
[void]$sb.AppendLine("static const uint16_t logo_c[$($W * $H)] = {"); [void]$sb.Append($cols.ToString()); [void]$sb.AppendLine('};')
[void]$sb.AppendLine("static const uint8_t logo_a[$($W * $H)] = {"); [void]$sb.Append($alp.ToString()); [void]$sb.AppendLine('};')
[void]$sb.AppendLine("const ArtImage artBakedLogo = {$W, $H, logo_c, logo_a};")
[System.IO.File]::WriteAllText("$root\src\logo_data.c", $sb.ToString())
Write-Host "wrote src/logo_data.c (banner.png written too)"
